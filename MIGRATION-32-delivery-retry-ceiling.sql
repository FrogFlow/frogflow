-- MIGRATION-32: потолок автоматических повторов выдачи заказа.
--
-- Блок 1.7 плана работ (третий заход): processPendingDeliveries() поднимает
-- каждый заказ, зависший в "delivering" больше 2 минут, бесконечно — без
-- счётчика попыток и без сдачи. Покупатель, заблокировавший бота, получал
-- попытку каждые 2 минуты вечно, а сбой каждой попытки глушился в логе крона.
--
-- Новая колонка считает подряд идущие неудачные попытки для ТЕКУЩЕЙ позиции
-- заказа (delivery_index). Как только их накопится больше MAX_DELIVERY_RETRIES
-- (см. orders.server.ts), код перестаёт пытаться и помечает материал как
-- требующий ручной отправки продавцом — вместо того чтобы крутить крон
-- бесконечно.
alter table public.orders
  add column if not exists delivery_retry_count integer not null default 0;

comment on column public.orders.delivery_retry_count is
  'Подряд идущие неудачные автоматические попытки выдачи текущей позиции заказа (delivery_index). Сбрасывается на 0 при успехе или при сдаче на ручную выдачу.';
