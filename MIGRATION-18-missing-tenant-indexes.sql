-- Индексы по bot_id на двух таблицах, которые их не получили при MIGRATION-01.
--
-- 25 из 27 таблиц с bot_id были проиндексированы по нему тогда же, когда
-- сама колонка появилась (см. MIGRATION-01-tenancy-foundation.sql). Эти две
-- таблицы просто выпали из списка — не по каким-то особым причинам, судя по
-- всему, недосмотр.
--
-- Таблицы маленькие (product_material_files — 28 строк, vip_tariffs — 10 на
-- момент написания), так что дело не в скорости запросов сегодня, а в
-- аккуратности: RLS-политика tenant_isolation фильтрует каждую выборку по
-- bot_id = current_bot_id(), и без индекса это последовательное сканирование
-- на любом объёме, до которого таблицы рано или поздно дорастут.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

CREATE INDEX IF NOT EXISTS idx_product_material_files_bot_id
  ON public.product_material_files (bot_id);

CREATE INDEX IF NOT EXISTS idx_vip_tariffs_bot_id
  ON public.vip_tariffs (bot_id);

COMMIT;
