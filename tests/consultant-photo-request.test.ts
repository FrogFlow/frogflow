import { describe, expect, it } from "vitest";
import { asksForProductPhoto } from "../src/lib/consultant/validate";

/**
 * Живой диалог 21.09: «34/40, можете отправить фото в сравнении с мобильным
 * телефоном, чтобы оценить размер?» Бот ответил, что фото отправлять не может,
 * и позвал в бутик — покупателю из Алматы, который спрашивал про полотенце
 * 34х40 и ехать никуда не собирался. Продавец попросил: просят фото — пусть
 * менеджер получит сообщение.
 *
 * Фотографий у консультанта нет вовсе: в каталоге только название, размер,
 * цвет, состав и цена. Ответить на такую просьбу может только человек.
 */
describe("просьба прислать фото", () => {
  it("ловит ту самую просьбу из диалога", () => {
    expect(
      asksForProductPhoto("34/40, можете отправить фото в сравнении с мобильным телефоном, чтобы оценить размер?"),
    ).toBe(true);
  });

  it("ловит другие способы попросить", () => {
    expect(asksForProductPhoto("Можно фото этого матраса?")).toBe(true);
    expect(asksForProductPhoto("Скиньте фотки пожалуйста")).toBe(true);
    expect(asksForProductPhoto("Есть ли фото в интерьере?")).toBe(true);
    expect(asksForProductPhoto("Пришлите видео как выглядит")).toBe(true);
    expect(asksForProductPhoto("покажите картинку")).toBe(true);
  });

  it("упоминание фото без просьбы просьбой не считает", () => {
    expect(asksForProductPhoto("Спасибо за фото")).toBe(false);
    expect(asksForProductPhoto("На фото у вас были синие")).toBe(false);
  });

  it("присланное покупателем фото — не просьба прислать", () => {
    // Эту строку мы составляем сами, описывая вложение. Иначе каждое фото от
    // покупателя дёргало бы менеджера.
    expect(
      asksForProductPhoto("[Клиент прислал фото/картинку без текста. Поблагодарите за фото и уточните, какой товар]"),
    ).toBe(false);
    expect(
      asksForProductPhoto("[Клиент отправил голосовое сообщение. Попросите написать текстом]"),
    ).toBe(false);
  });

  it("обычные вопросы не трогает", () => {
    expect(asksForProductPhoto("Плотность их какая?")).toBe(false);
    expect(asksForProductPhoto("Какая стоимость лицевых полотенец Uchino?")).toBe(false);
    expect(asksForProductPhoto("")).toBe(false);
  });
});
