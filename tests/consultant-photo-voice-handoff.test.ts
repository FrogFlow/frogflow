import { describe, expect, it } from "vitest";
import { asksForProductPhoto, isVoiceMessagePlaceholder } from "../src/lib/consultant/validate";

/**
 * Продавец: «если хотят фото, картинок, пишут сообщение голосом — сразу на
 * менеджера переключать и сообщать об этом».
 *
 * Раньше бот на просьбу о фото передавал вопрос и продолжал разговор, а на
 * голосовое просил написать текстом. И то и другое человек сделает быстрее:
 * фотографий у консультанта нет вовсе, голосовые он не слышит.
 */
describe("голосовое сообщение узнаётся", () => {
  it("по нашей же строке-заглушке", () => {
    expect(
      isVoiceMessagePlaceholder(
        "[Клиент отправил голосовое сообщение. Попросите написать текстом, так как бот принимает только текстовые сообщения]",
      ),
    ).toBe(true);
  });

  it("присланное фото голосовым не считается", () => {
    // У него своя заглушка и своё поведение.
    expect(
      isVoiceMessagePlaceholder("[Клиент прислал фото/картинку без текста. Поблагодарите за фото]"),
    ).toBe(false);
  });

  it("обычный текст — не голосовое", () => {
    expect(isVoiceMessagePlaceholder("Сколько стоит полотенце?")).toBe(false);
    expect(isVoiceMessagePlaceholder("")).toBe(false);
    // Слово «голосовое» в живой речи заглушкой не является.
    expect(isVoiceMessagePlaceholder("можно голосовое отправить?")).toBe(false);
  });
});

describe("просьба о фото ведёт к менеджеру", () => {
  it("узнаётся так же, как и раньше", () => {
    expect(asksForProductPhoto("Можно их видео или фото?")).toBe(true);
    expect(asksForProductPhoto("Скиньте картинки")).toBe(true);
  });

  it("присланное покупателем фото просьбой не считается", () => {
    expect(
      asksForProductPhoto("[Клиент прислал фото/картинку без текста. Поблагодарите за фото]"),
    ).toBe(false);
  });
});
