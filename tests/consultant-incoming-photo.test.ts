import { describe, expect, it } from "vitest";
import {
  asksForProductPhoto,
  cleanNotUnderstoodApology,
  isIncomingPhotoPlaceholder,
  isVoiceMessagePlaceholder,
} from "../src/lib/consultant/validate";

/**
 * Живой диалог 22.09, @kris.koteneva из Москвы. Она прислала снимок полотенец
 * с птичками — показала ровно то, что хотела купить. В ответ пришло:
 *
 *   Спасибо за фото. К сожалению, я не вижу изображение в чате. Напишите,
 *   пожалуйста, текстом: • Какой товар вас интересует • Размер • Цвет или
 *   описание рисунка • Город доставки
 *
 * Заглушка, которую мы сами подставляли вместо вложения, несла модели
 * инструкцию «поблагодарите за фото и уточните, какой товар интересует» —
 * то есть мы сами и просили продолжать анкету. Правило продавца обратное:
 * прислали картинку — сразу менеджеру.
 */
describe("покупатель прислал фото", () => {
  it("узнаём заглушку вложения", () => {
    expect(isIncomingPhotoPlaceholder("[Клиент прислал фото или картинку]")).toBe(true);
    // Старая формулировка ещё лежит в истории диалогов — её тоже узнаём.
    expect(
      isIncomingPhotoPlaceholder("[Клиент прислал фото/картинку без текста. Поблагодарите за фото]"),
    ).toBe(true);
  });

  it("не путаем с голосовым и с просьбой прислать фото", () => {
    expect(isIncomingPhotoPlaceholder("[Клиент отправил голосовое сообщение]")).toBe(false);
    expect(isVoiceMessagePlaceholder("[Клиент прислал фото или картинку]")).toBe(false);
    expect(isIncomingPhotoPlaceholder("Можете прислать фото полотенец?")).toBe(false);
  });

  it("присланное фото не считается просьбой прислать фото", () => {
    expect(asksForProductPhoto("[Клиент прислал фото или картинку]")).toBe(false);
  });
});

/**
 * Там же: на «Мне голландские с птичками понравились» бот ответил «Извините,
 * я не совсем понял» — и следующей же фразой сам назвал и страну, и бренд.
 */
describe("извинение за непонимание", () => {
  it("вырезается, ответ по существу остаётся", () => {
    expect(
      cleanNotUnderstoodApology(
        "Извините, я не совсем понял. В нашем каталоге есть голландский бренд PIP Studio.",
      ),
    ).toBe("В нашем каталоге есть голландский бренд PIP Studio.");
  });

  it("если это был весь ответ — оставляем, молчание хуже", () => {
    const only = "Извините, я не совсем понял.";
    expect(cleanNotUnderstoodApology(only)).toBe(only);
  });

  it("обычный ответ не трогаем", () => {
    const normal = "Полотенца PIP Studio 55x100 — 18 000 ₸. В наличии.";
    expect(cleanNotUnderstoodApology(normal)).toBe(normal);
  });
});
