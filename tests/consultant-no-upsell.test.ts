import { describe, expect, it } from "vitest";
import { cleanUpsellPressure, pushesToBuyMore } from "../src/lib/consultant/validate";

/**
 * Живой ответ, который продавец обвёл красным: «Какой размер вас больше
 * интересует, или возьмёте оба?» — «вот так тут давить на клиента нельзя,
 * прямо ему запретите».
 *
 * Уйти должен только навязчивый хвост: сам вопрос про размер нормальный и
 * нужный, без него ответ повиснет.
 */
describe("дожим срезается, вопрос остаётся", () => {
  it("та самая фраза", () => {
    expect(cleanUpsellPressure("Какой размер вас больше интересует, или возьмёте оба?")).toBe(
      "Какой размер вас больше интересует?",
    );
  });

  it("другие способы дожать тем же хвостом", () => {
    expect(cleanUpsellPressure("Какой размер интересует, а может возьмёте оба?")).toBe(
      "Какой размер интересует?",
    );
    expect(cleanUpsellPressure("Что выбираете — берите сразу два, так выгоднее.")).toBe(
      "Что выбираете.",
    );
    expect(cleanUpsellPressure("Какой цвет нужен, почему бы не взять оба?")).toBe(
      "Какой цвет нужен?",
    );
  });

  it("предложение целиком из уговора убирается", () => {
    expect(
      cleanUpsellPressure(
        "Полотенце 35х50 — 27 000 ₸. Рекомендую взять оба размера. Какой размер вас интересует?",
      ),
    ).toBe("Полотенце 35х50 — 27 000 ₸. Какой размер вас интересует?");
  });

  it("узнаёт уговор отдельной проверкой", () => {
    expect(pushesToBuyMore("Возьмите оба")).toBe(true);
    expect(pushesToBuyMore("Советую взять сразу два")).toBe(true);
    expect(pushesToBuyMore("Может быть возьмёте комплектом")).toBe(true);
  });
});

describe("нормальный текст не трогается", () => {
  it("обычный вопрос и перечень цен", () => {
    const reply =
      "Uchino Полотенце махровое для ног Merveille, 35х50 см — 27 000 ₸. Какой размер вас интересует?";
    expect(cleanUpsellPressure(reply)).toBe(reply);
  });

  it("покупатель сам просит оба — это не дожим с нашей стороны", () => {
    // Чистится только наш текст; фраза про наличие обоих размеров остаётся.
    const reply = "Оба размера есть в наличии.";
    expect(cleanUpsellPressure(reply)).toBe(reply);
    expect(pushesToBuyMore("Оба размера есть в наличии.")).toBe(false);
  });

  it("если дожим был всем ответом, пустоту не отправляем", () => {
    const reply = "Возьмите оба.";
    expect(cleanUpsellPressure(reply)).toBe(reply);
  });
});
