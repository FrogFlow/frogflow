import { describe, expect, it } from "vitest";
import { promisesManagerFollowUp } from "../src/lib/consultant/validate";

/**
 * Живой диалог 21.09, полотенца Uchino. Покупатель спросил про плотность, бот
 * сказал «Уточню этот момент у менеджера и вернусь с ответом», следом
 * «проверю информацию о плотности полотенец Uchino и свяжусь с вами с
 * ответом» — и не вызвал ask_manager. В списке задач панели за этот час не
 * появилось ни строки: менеджер не узнал, покупатель остался ждать.
 *
 * Поэтому обещание ловится по тексту ответа. Продавец спросил прямо: «он
 * отправит сообщение в таком случае? Или как?» — теперь отправит.
 */
describe("обещание вернуться с ответом", () => {
  it("ловит обе фразы из того самого диалога", () => {
    expect(
      promisesManagerFollowUp("Уточню этот момент у менеджера и вернусь с ответом. Пока могу помочь с чем-то ещё?"),
    ).toBe(true);
    expect(
      promisesManagerFollowUp("Хорошо, проверю информацию о плотности полотенец Uchino и свяжусь с вами с ответом."),
    ).toBe(true);
  });

  it("ловит другие способы сказать то же самое", () => {
    expect(promisesManagerFollowUp("Спрошу у менеджера и вернусь с ответом")).toBe(true);
    expect(promisesManagerFollowUp("Узнаю у менеджера точный состав")).toBe(true);
    expect(promisesManagerFollowUp("Уточню у менеджера")).toBe(true);
  });

  it("не срабатывает на обычный ответ с товарами", () => {
    expect(promisesManagerFollowUp("Махровые полотенца Uchino 50х70: Zero Twist — 32 000 ₸")).toBe(false);
    expect(promisesManagerFollowUp("Какой размер полотенец вас интересует?")).toBe(false);
    expect(promisesManagerFollowUp("Адрес: г. Алматы, ул. Сатпаева, 3")).toBe(false);
  });

  it("не путает с передачей на покупку", () => {
    // Здесь менеджер свяжется по заказу, а не с ответом на вопрос: диалог уже
    // на паузе, задачу заводить не нужно.
    expect(
      promisesManagerFollowUp("Менеджер свяжется с вами по номеру +77002538888 для подтверждения доставки в Алматы"),
    ).toBe(false);
  });
});
