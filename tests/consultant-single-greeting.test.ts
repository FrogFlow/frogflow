import { describe, expect, it } from "vitest";
import { stripRepeatGreeting } from "../src/lib/consultant/style";

/**
 * Продавец о живом диалоге: «здесь бот здоровается два раза — если человек
 * выбрал страну вначале, там же есть здравствуйте».
 *
 * Так и было: приветствие стоит в вопросе про страну, покупатель отвечает
 * «Россия», и следующий ответ снова начинается со «Здравствуйте».
 */
describe("второе приветствие срезается", () => {
  it("та самая фраза из диалога", () => {
    expect(
      stripRepeatGreeting(
        "Здравствуйте. Коврики для ванной у нас есть разных размеров и марок. Скажите, какой размер вас интересует?",
      ),
    ).toBe("Коврики для ванной у нас есть разных размеров и марок. Скажите, какой размер вас интересует?");
  });

  it("другие формы приветствия", () => {
    expect(stripRepeatGreeting("Добрый день, полотенца есть в наличии.")).toBe(
      "Полотенца есть в наличии.",
    );
    expect(stripRepeatGreeting("Привет! Матрасы от 450 000 ₸.")).toBe("Матрасы от 450 000 ₸.");
    expect(stripRepeatGreeting("Доброе утро — коврики от 24 000 ₸.")).toBe("Коврики от 24 000 ₸.");
  });

  it("строчную букву после среза поднимает", () => {
    expect(stripRepeatGreeting("Здравствуйте, коврики есть в наличии.")).toBe(
      "Коврики есть в наличии.",
    );
  });
});

describe("что трогать нельзя", () => {
  it("ответ без приветствия остаётся прежним", () => {
    const reply = "Коврики для ванной от 24 000 ₸. Какой размер вас интересует?";
    expect(stripRepeatGreeting(reply)).toBe(reply);
  });

  it("приветствие внутри текста не трогается", () => {
    // Режется только ведущее: «передайте здравствуйте» — это не приветствие
    // от бота.
    const reply = "Менеджер передаст вам здравствуйте и ответит по цене.";
    expect(stripRepeatGreeting(reply)).toBe(reply);
  });

  it("если приветствие было всем сообщением, пустоту не отправляем", () => {
    expect(stripRepeatGreeting("Здравствуйте.")).toBe("Здравствуйте.");
    expect(stripRepeatGreeting("Добрый день")).toBe("Добрый день");
  });
});
