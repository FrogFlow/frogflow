-- ═══════════════════════════════════════════════════════════════════════════
-- bot_events.kind — словарь оказался уже, чем набор действий панели.
--
-- В MIGRATION-08 список был ограничен шестью значениями. С тех пор код дважды
-- обошёл ограничение, подставляя неточный вид вместо настоящего:
--   • перевод в suspended пишется как 'pause'   (bots.server.ts, setBotStatus)
--   • переустановка вебхука пишется как 'onboard' (bots.server.ts, requestWebhookSetup)
-- А сборка блока переменных не пишется вообще: вставка с kind='env_block'
-- падает на этом CHECK, и ошибка нигде не проверяется — журнал молча теряет
-- запись о том, что оператору выдали ключ арендатора клиента.
--
-- Расширяем словарь до тех действий, которые панель реально совершает.
-- CHECK не убираем: он ловит опечатки в kind, а это ровно то, из-за чего
-- запись потерялась бы снова.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.bot_events DROP CONSTRAINT IF EXISTS bot_events_kind_check;

ALTER TABLE public.bot_events
  ADD CONSTRAINT bot_events_kind_check CHECK (kind IN (
    'module_on',   -- модуль включён
    'module_off',  -- модуль выключен
    'pause',       -- бот поставлен на паузу
    'resume',      -- бот снят с паузы
    'suspend',     -- бот приостановлен (раньше писался как 'pause')
    'onboard',     -- клиент заведён
    'webhook',     -- вебхук переустановлен (раньше писался как 'onboard')
    'env_block',   -- собран блок переменных окружения
    'meta',        -- изменены данные клиента
    'message'      -- владельцу отправлено сообщение
  ));

COMMIT;

