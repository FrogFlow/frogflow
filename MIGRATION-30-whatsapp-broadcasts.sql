-- ═══════════════════════════════════════════════════════════════════════════
-- MIGRATION 30 — рассылки в WhatsApp поверх существующей механики.
--
-- Таблицы `broadcasts` и `broadcast_recipients` уже умеют всё, что нужно:
-- очередь, пакетная отправка, статус по каждому получателю, счётчики
-- отправленных/упавших/заблокировавших. Заводить под WhatsApp вторую такую же
-- пару было бы дублированием — добавляем канал и то, чего у телеграмной
-- рассылки нет в принципе: ссылку на одобренный шаблон Meta.
--
-- Почему шаблон обязателен. Вне 24-часового окна WhatsApp не пропускает
-- свободный текст, а рассылка по базе — это ровно тот случай: люди писали
-- когда угодно, у большинства окно давно закрыто. Поэтому у WhatsApp-рассылки
-- текст сообщения не свой, а заданный одобренным шаблоном; `message_text`
-- остаётся для показа продавцу в панели.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.broadcasts
  -- 'telegram' | 'whatsapp'. DEFAULT сохраняет поведение всех уже созданных
  -- рассылок: они телеграмные, и переписывать их не нужно.
  ADD COLUMN IF NOT EXISTS channel           TEXT NOT NULL DEFAULT 'telegram',
  -- Аккаунт WhatsApp в Zernio, от которого идёт отправка.
  ADD COLUMN IF NOT EXISTS account_id        TEXT,
  ADD COLUMN IF NOT EXISTS template_name     TEXT,
  ADD COLUMN IF NOT EXISTS template_language TEXT,
  -- Значения переменных шаблона, одним плоским массивом в порядке подстановки
  -- (так их принимает Zernio: сначала переменные заголовка, потом тела, потом
  -- по одному значению на динамическую кнопку-ссылку).
  ADD COLUMN IF NOT EXISTS template_params   JSONB NOT NULL DEFAULT '[]'::jsonb;

-- Очередь разбирается по статусу; канал добавлен в индекс, потому что
-- обработчик берёт следующую рассылку своего канала, а не любую.
CREATE INDEX IF NOT EXISTS idx_broadcasts_channel_status
  ON public.broadcasts(channel, status, created_at);

-- Получателю WhatsApp нужен номер, а не chat_id. Держим его отдельной
-- колонкой, а не выводим каждый раз из bot_users: покупатель может сменить
-- ключ или быть удалён, а отчёт о рассылке обязан остаться воспроизводимым.
ALTER TABLE public.broadcast_recipients
  ADD COLUMN IF NOT EXISTS phone TEXT;

COMMIT;
