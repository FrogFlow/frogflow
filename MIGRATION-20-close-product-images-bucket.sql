-- Закрыть бакет product-images — открытый вопрос с первого обследования
-- (ANALYSIS.md), теперь проверенный и решённый.
--
-- Подтверждено эмпирически: анонимным ключом бакет листится
-- (POST /storage/v1/object/list/product-images отдаёт реальные имена файлов
-- всех арендаторов вперемешку — префикса bot_id в именах нет, та же картина,
-- что была у product-files до его закрытия).
--
-- Подтверждено по коду: ни один путь показа картинки в проекте не использует
-- публичный URL бакета. Все ссылки — на серверный прокси
-- /api/public/img/… (src/routes/api/public/img/$.ts), который сам качает
-- файл под service_role и не зависит от публичности бакета:
--   • админка (admin.products.tsx, admin.payment-methods.tsx,
--     admin.broadcast.tsx) — src="/api/public/img/…";
--   • сообщения ботов (bot.server.ts:115, vip-bot.server.ts:88) — та же
--     ссылка.
-- `getPublicUrl` в проекте зовётся один раз и для другого бакета
-- (instruction-videos, см. bot.server.ts:315) — там это осознанно и не
-- меняется.
--
-- В отличие от product-files это не критично (витринные картинки и так
-- показываются публично — в этом их смысл), но открытая листинг-выдача по
-- всем арендаторам сразу — лишняя поверхность, которой ничто не пользуется.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

UPDATE storage.buckets SET public = false WHERE id = 'product-images';
DROP POLICY IF EXISTS "Public Read product-images" ON storage.objects;

COMMIT;

