-- ═══════════════════════════════════════════════════════════════════════════
-- К истории можно привязать несколько товаров, а не один.
--
-- Продавец снимает сторис, в которой лежат простыня, пододеяльник и наволочки,
-- и хочет, чтобы бот знал их все. В MIGRATION-70 товар был ровно один:
-- product_name, product_price_kzt, product_id — три колонки на одну позицию.
--
-- Миграция ТОЛЬКО ДОБАВЛЯЕТ колонку. Старые три остаются и продолжают хранить
-- первый товар списка: на них смотрит уже выложенный код, и ломать его на
-- живых клиентах ради нового поля незачем. Заполненный products выигрывает,
-- пустой — читается старым путём.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE public.story_product_tags
  ADD COLUMN IF NOT EXISTS products JSONB;

COMMENT ON COLUMN public.story_product_tags.products IS
  'Список товаров истории: [{"id":"…","name":"…","price_kzt":123}]. Первый дублируется в product_* ради обратной совместимости.';
