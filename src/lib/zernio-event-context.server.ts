import { AsyncLocalStorage } from "node:async_hooks";
import crypto from "node:crypto";

/**
 * Контекст обрабатываемого события Zernio.
 *
 * Нужен ради заголовка `Idempotency-Key` при отправке сообщений. Ключ обязан
 * быть одинаковым при повторной обработке того же события и разным у разных
 * событий — иначе одно из двух: либо клиент получит сообщение дважды, либо
 * законный повтор («не понял, повторите» на два одинаковых вопроса) будет
 * молча проглочен как дубль.
 *
 * Отправка вызывается из двух десятков мест внутри обработчика, и протаскивать
 * идентификатор события параметром через всю цепочку значило бы поменять
 * два десятка сигнатур и полагаться на то, что в новом коде о нём вспомнят.
 * AsyncLocalStorage выставляет его один раз на входе в обработку.
 */
const store = new AsyncLocalStorage<{ eventId: string }>();

/** Выполнить обработку события так, чтобы отправки внутри знали его идентификатор. */
export function runWithZernioEvent<T>(eventId: string | null, task: () => Promise<T>): Promise<T> {
  if (!eventId) return task();
  return store.run({ eventId }, task);
}

/**
 * Ключ идемпотентности для одной отправки.
 *
 * Складывается из идентификатора события и тела запроса: повтор того же события
 * повторит ту же последовательность тел и получит те же ключи — Zernio вернёт
 * исходные ответы вместо новых отправок. Разные сообщения внутри одного события
 * дают разные ключи и уходят все.
 *
 * Вне обработки события (например, отправка из админки руками) ключа нет —
 * там повтор осмысленный и подавлять его нельзя.
 */
export function idempotencyKeyFor(body: unknown): string | undefined {
  const context = store.getStore();
  if (!context) return undefined;
  return crypto
    .createHash("sha256")
    .update(`${context.eventId}:${JSON.stringify(body)}`)
    .digest("hex");
}
