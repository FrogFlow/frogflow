/**
 * Разделение двух ролей одного и того же приложения.
 *
 * Репозиторий один, бандл один, а деплоя два вида: панель оператора
 * (CONTROL_PLANE=1) и деплой клиента (переменная не задана). Каждый должен
 * отдавать 404 на пути другого — не прятать ссылку, а именно отказывать.
 *
 * Про /operator на клиентском деплое — requireOperator() в
 * lib/operator/guard.server.ts. Здесь зеркальная половина: клиентское
 * приложение (магазин, /admin, /login) на деплое панели.
 *
 * Зачем это нужно, а не «просто задать ADMIN_PASSWORD»: у панели нет BOT_ID и
 * нет ключа арендатора, поэтому её подключение к базе идёт под service_role в
 * обход RLS. Клиентская админка, открытая на таком деплое, показывает и правит
 * данные ВСЕХ клиентов сразу. Пароль здесь — не тот уровень защиты: правильный
 * ответ в том, что этих страниц на панели не существует.
 */
export function isControlPlane(): boolean {
  return process.env.CONTROL_PLANE === "1";
}

/**
 * Первой строкой серверных функций клиентской админки. Тот же текст ошибки,
 * что и у несуществующего пути: панель не должна подтверждать даже наличие
 * такой функции.
 */
export function assertTenantDeployment(): void {
  if (isControlPlane()) {
    throw new Error("Not found");
  }
}
