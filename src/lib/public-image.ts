import { requireAppOrigin } from "./app-origin.server";

/**
 * Публичная ссылка на картинку из хранилища.
 *
 * Отдельным модулем, потому что нужна двум ботам сразу: Telegram шлёт по ней
 * фото товара и QR-код реквизитов, а WhatsApp — фото в карточке товара. Раньше
 * функция жила внутри `bot.server.ts` и не экспортировалась, так что второму
 * боту оставалось либо тащить её оттуда (а вместе с ней и весь
 * трёхтысячестрочный модуль телеграм-бота), либо завести вторую копию — и
 * вторая копия разошлась бы с первой в первый же раз, когда поменяется путь
 * или бакет.
 *
 * `path` — ключ внутри бакета `product-images`; маршрут
 * `/api/public/img/$` разбирает префиксы `broadcast-images/` и
 * `instagram-media/` отдельно, а всё остальное считает ключом витринных фото.
 */
export function imageUrl(path: string): string {
  return `${requireAppOrigin()}/api/public/img/${path}`;
}
