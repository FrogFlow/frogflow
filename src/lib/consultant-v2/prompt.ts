/**
 * Промпт консультанта v2 (ИИ-менеджер BOVI).
 *
 * В v1 правила росли на каждую жалобу и дошли до 39 тысяч знаков: модель
 * читала двадцать страниц запретов, половина из которых писалась под
 * конкретный сбой. Здесь — роль, цель, как писать, как продавать и факты
 * магазина. Остальное модель берёт из данных: прайс, база знаний,
 * инструменты. Правило добавляется сюда, только если без него модель
 * ошибается на эталонном наборе, а не на одной жалобе.
 *
 * Стиль задан примерами живого менеджера BOVI: из её ответов в директе видно,
 * как здесь пишут — «50*100 и 70*140», «Коврик 35*50=6400 руб».
 */

import type { ConsultantProduct } from "@/lib/consultant/catalog";

export const V2_PROMPT_VERSION = "v2.1";

/**
 * Прайс для промпта v2 — только в тенге. Рублёвой колонки нет: рубли
 * считает код (currency.ts), модель их в длинном прайсе путает.
 */
export function formatCatalogForV2(catalog: ConsultantProduct[]): string {
  const inStock = catalog.filter((p) => p.stock);
  if (inStock.length === 0) return "АКТУАЛЬНЫЙ АССОРТИМЕНТ: сейчас пусто.";
  const lines = [
    "АКТУАЛЬНЫЙ АССОРТИМЕНТ — всё в наличии. Формат строки:",
    "• название | размер | категория | цена ₸ | цв: расцветки | сост: состав",
  ];
  for (const p of inStock) {
    const parts = [p.name];
    if (p.size) parts.push(p.size);
    if (p.category) parts.push(p.category);
    parts.push(`${p.price_kzt.toLocaleString("ru-RU")} ₸`);
    if (p.colors.length > 0) parts.push(`цв: ${p.colors.join(", ")}`);
    if (p.material) parts.push(`сост: ${p.material}`);
    lines.push(`• ${parts.join(" | ")}`);
  }
  return lines.join("\n");
}

