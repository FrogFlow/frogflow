/**
 * Публичный адрес этого деплоя — единственный источник.
 *
 * До этого файла та же функция была скопирована в пяти местах под четырьмя
 * именами (`appUrl`, `originFromState`, `publicAppOrigin` ×2 и две копии прямо
 * в instagram.functions.ts), и в каждой копии последним запасным вариантом
 * стоял чужой домен — деплой самого первого бота. Пока клиент был один, это
 * было незаметно. В общей базе это значило: деплой, которому не задали
 * PUBLIC_APP_URL, уводил покупателей в чужой магазин, показывал чужие картинки
 * товаров и отправлял колбэки Robokassa на чужой хост.
 *
 * Поэтому запасного домена здесь нет вообще. Деплой, который не знает своего
 * адреса, настроен неправильно, и это должно быть видно сразу — как и
 * отсутствие BOT_ID.
 */

/** Адрес деплоя без хвостового слэша; пустая строка, если определить нельзя. */
export function appOrigin(): string {
  return (
    process.env.PUBLIC_APP_URL ||
    (process.env.VERCEL_PROJECT_PRODUCTION_URL
      ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`
      : "") ||
    (process.env.VERCEL_URL ? `https://${process.env.VERCEL_URL}` : "")
  )
    .trim()
    .replace(/\/$/, "");
}

/**
 * То же, но с громкой ошибкой вместо пустой строки. Нужен там, где адрес
 * попадает в ссылку покупателю или в реквизиты платёжного шлюза: пустой
 * origin даёт битую ссылку, а неверный — уводит деньги и людей не туда.
 *
 * На Vercel VERCEL_PROJECT_PRODUCTION_URL проставляется всегда, так что на
 * рабочем деплое это не выстрелит.
 */
export function requireAppOrigin(): string {
  const origin = appOrigin();
  if (!origin) {
    throw new Error(
      "Не удалось определить публичный адрес деплоя: задайте PUBLIC_APP_URL " +
        "в переменных окружения (например, https://your-app.vercel.app).",
    );
  }
  return origin;
}
