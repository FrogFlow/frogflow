-- ═══════════════════════════════════════════════════════════════════════════
-- nightly_orders_maintenance() перестаёт перенумеровывать заказы бота,
-- у которого номера и так уже плотные (Блок 3.5, кейс 2).
--
-- ── Что было ──
-- renumber_orders() (MIGRATION-23) каждую ночь в 00:00 UTC переписывает
-- ВСЕ заказы КАЖДОГО бота дважды (фаза 1: увести order_no на +1 000 000 000,
-- фаза 2: расставить 1..N заново) — независимо от того, случилось ли за
-- сутки хоть одно удаление, из-за которого в номерах вообще могла
-- образоваться дыра. На семи арендаторах и ~500 живых заказах это уже
-- ~9500 переписанных версий строк за ночь, и растёт линейно с базой.
--
-- MIGRATION-28 заморозила display_no — тот номер, что видел и продолжает
-- видеть покупатель, renumber_orders() больше не трогает вообще. Живым
-- потребителем перенумерации осталась ровно одна вещь: «номер в списке
-- /admin/orders должен идти 1..N без дыр» — явное пожелание оператора
-- (см. комментарий в MIGRATION-23), а не забытый побочный эффект. Значит
-- убирать перенумерацию совсем нельзя — но гонять её на ботах, где дыры
-- заведомо нет, тоже незачем.
--
-- ── Решение ──
-- order_counters.last_no после каждого renumber_orders() всегда равен
-- количеству живых заказов бота (см. её же тело: `last_no = v_count`), а
-- дальше растёт на 1 на каждый новый заказ (assign_order_no(), MIGRATION-03)
-- ровно вместе с count(*) — то есть пока ни одна строка не удалена,
-- count(*) = last_no неизменно. Удаление (эта же ночная чистка застрявших
-- awaiting_confirmation, или ручное «Удалить» в /admin/orders) двигает
-- count(*) вниз, а last_no остаётся прежним — вот и вся дыра, и вот
-- единственный надёжный признак «этому боту сегодня нужна перенумерация».
--
-- Бот без строки в order_counters (ещё не было ни одного заказа, значит и
-- renumber_orders() ни разу не вызывалась) считается «грязным» и получает
-- обычный первый проход — прежнее поведение для новых арендаторов не
-- меняется.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

CREATE OR REPLACE FUNCTION public.nightly_orders_maintenance() RETURNS void
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  b record;
BEGIN
  DELETE FROM public.orders
  WHERE status = 'awaiting_confirmation'
    AND created_at < now() - interval '7 days';

  FOR b IN
    SELECT bt.id
    FROM public.bots bt
    LEFT JOIN public.order_counters oc ON oc.bot_id = bt.id
    WHERE oc.bot_id IS NULL
       OR oc.last_no IS DISTINCT FROM (
         SELECT count(*) FROM public.orders o WHERE o.bot_id = bt.id
       )
  LOOP
    PERFORM public.renumber_orders(b.id);
  END LOOP;
END $$;

COMMIT;

