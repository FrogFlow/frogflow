-- Продажа в Instagram Direct: почта покупателя.
--
-- Зачем почта вообще. Instagram Direct не принимает вложениями документы —
-- только картинки, видео и аудио (см. таблицу возможностей в документации
-- Zernio). А продают тут PDF и ZIP с методическими материалами. То есть
-- выдать купленное прямо в переписке нельзя ни при какой доработке кода:
-- это ограничение платформы, а не наше.
--
-- Второе ограничение того же рода — окно в 24 часа: написать покупателю
-- позже суток с его последнего сообщения Instagram не даст. Оплатили
-- вечером, продавец подтвердил утром — сообщение уже не уйдёт.
--
-- Почта снимает оба ограничения разом и заодно даёт покупателю то, что у
-- него останется навсегда, а не потеряется в переписке.
--
-- `customer_email` кладётся в заказ (в нём и выдача), `email` — в карточку
-- пользователя, чтобы у постоянного покупателя не спрашивать адрес заново.
--
-- Отдельного кода товара не заводим: клиенты уже кладут номер первым
-- ключевым словом («018, пазлы, карточки…» у товара «018. Набор …»), и
-- покупатели этот номер пишут. Заводить второе поле под то же самое значило
-- бы получить два источника правды и требовать заполнить 486 товаров заново.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.orders   ADD COLUMN IF NOT EXISTS customer_email text;
ALTER TABLE public.bot_users ADD COLUMN IF NOT EXISTS email          text;

COMMENT ON COLUMN public.orders.customer_email IS
  'Куда отправить материалы. Основной способ выдачи для заказов из Instagram: Direct не принимает документы вложением.';
COMMENT ON COLUMN public.bot_users.email IS
  'Последняя известная почта покупателя — чтобы не спрашивать её при каждом заказе.';

-- Выборка «заказы, которым ещё не отправили письмо» и разбор обращений по
-- почте идут по этому полю, поэтому индекс частичный: пустых значений здесь
-- заведомо большинство, и в индексе им делать нечего.
CREATE INDEX IF NOT EXISTS idx_orders_customer_email
  ON public.orders (customer_email)
  WHERE customer_email IS NOT NULL;

COMMIT;
