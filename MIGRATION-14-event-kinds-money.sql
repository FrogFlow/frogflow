-- ═══════════════════════════════════════════════════════════════════════════
-- Досбор словаря bot_events.kind: деньги и политика неоплаты.
--
-- MIGRATION-12 расширил словарь до действий с ботом, но подписки остались за
-- бортом: запись платежа, его удаление и смена политики неоплаты до сих пор
-- пишутся видом 'message' с настоящим действием, спрятанным в payload.action.
-- В журнале это читается как «владельцу отправлено сообщение» — хотя никакого
-- сообщения не было. Для журнала, по которому потом разбирают спорную оплату,
-- это худший вид неточности.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

ALTER TABLE public.bot_events DROP CONSTRAINT IF EXISTS bot_events_kind_check;

ALTER TABLE public.bot_events
  ADD CONSTRAINT bot_events_kind_check CHECK (kind IN (
    'module_on',   -- модуль включён
    'module_off',  -- модуль выключен
    'pause',       -- бот поставлен на паузу
    'resume',      -- бот снят с паузы
    'suspend',     -- бот приостановлен
    'onboard',     -- клиент заведён
    'webhook',     -- вебхук переустановлен
    'env_block',   -- собран блок переменных окружения
    'meta',        -- изменены данные клиента
    'payment',     -- записан или удалён платёж по подписке
    'policy',      -- изменена политика неоплаты
    'message'      -- владельцу отправлено сообщение
  ));

COMMIT;

